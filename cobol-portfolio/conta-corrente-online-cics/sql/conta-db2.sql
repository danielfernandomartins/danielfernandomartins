CREATE TABLE CONTA_CORRENTE (
    NUM_CONTA   CHAR(10)      NOT NULL PRIMARY KEY,
    TITULAR     VARCHAR(30)   NOT NULL,
    STATUS      VARCHAR(10)   NOT NULL,
    SALDO       DECIMAL(11,2) NOT NULL DEFAULT 0,
    DT_ATUALIZACAO DATE       NOT NULL DEFAULT CURRENT DATE
);

CREATE INDEX IX_CONTA_STATUS
    ON CONTA_CORRENTE (STATUS);

-- Exemplo de consulta usada pelo programa COBOL/CICS
SELECT TITULAR, STATUS, SALDO
FROM CONTA_CORRENTE
WHERE NUM_CONTA = '0000012345';
