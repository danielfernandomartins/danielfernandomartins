-- Modelo didático compatível com conceitos de DB2
CREATE TABLE TRANSACAO_BANCARIA (
    ID_TRANSACAO      CHAR(10)      NOT NULL PRIMARY KEY,
    CONTA             CHAR(10)      NOT NULL,
    TIPO              VARCHAR(10)   NOT NULL,
    VALOR             DECIMAL(11,2) NOT NULL,
    STATUS            VARCHAR(12)   NOT NULL,
    DATA_PROCESSAMENTO DATE         NOT NULL DEFAULT CURRENT DATE
);

CREATE INDEX IX_TRANSACAO_CONTA
    ON TRANSACAO_BANCARIA (CONTA);

CREATE INDEX IX_TRANSACAO_STATUS
    ON TRANSACAO_BANCARIA (STATUS);

-- Consulta típica de conciliação
SELECT STATUS,
       COUNT(*) AS QUANTIDADE,
       SUM(VALOR) AS TOTAL
FROM TRANSACAO_BANCARIA
GROUP BY STATUS;
